func (a *App) GetAvailableSubtitles(url string) ([]SubtitleInfo, error) {
	ctx, cancel := context.WithTimeout(context.Background(), fetchTimeout)
	defer cancel()

	result, err := ytdlp.New().
		DumpJSON().
		ListSubs().
		Run(ctx, url)

	if err != nil {
		return nil, fmt.Errorf("failed to fetch subtitles: %w", err)
	}

	var info struct {
		Subtitles map[string][]struct {
			URL  string `json:"url"`
			Name string `json:"name"`
		} `json:"subtitles"`
		AutomaticCaptions map[string][]struct {
			URL  string `json:"url"`
			Name string `json:"name"`
		} `json:"automatic_captions"`
	}

	if err := json.Unmarshal([]byte(result.Stdout), &info); err != nil {
		return nil, err
	}

	subtitles := []SubtitleInfo{}

	for lang, subs := range info.Subtitles {
		for _, sub := range subs {
			subtitles = append(subtitles, SubtitleInfo{
				Language:        lang,
				LanguageName:    sub.Name,
				Format:          "vtt",
				URL:             sub.URL,
				IsAutoGenerated: false,
			})
		}
	}

	for lang, subs := range info.AutomaticCaptions {
		for _, sub := range subs {
			subtitles = append(subtitles, SubtitleInfo{
				Language:        lang,
				LanguageName:    sub.Name + " (auto)",
				Format:          "vtt",
				URL:             sub.URL,
				IsAutoGenerated: true,
			})
		}
	}

	return subtitles, nil
}

