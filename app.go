func (a *App) getSettingsFilePath() string {
	homeDir, _ := os.UserHomeDir()
	settingsDir := filepath.Join(homeDir, ".predator")
	os.MkdirAll(settingsDir, 0755)
	return filepath.Join(settingsDir, settingsFileName)
}

func (a *App) GetSettings() (AppSettings, error) {
	settingsMu.RLock()
	if currentSettings != nil {
		settings := *currentSettings
		settingsMu.RUnlock()
		return settings, nil
	}
	settingsMu.RUnlock()

	settingsFile := a.getSettingsFilePath()
	data, err := os.ReadFile(settingsFile)
	if err != nil {
		if os.IsNotExist(err) {
			defaults := getDefaultSettings()
			return defaults, nil
		}
		return AppSettings{}, err
	}

	var settings AppSettings
	if err := json.Unmarshal(data, &settings); err != nil {
		return AppSettings{}, err
	}

	settingsMu.Lock()
	currentSettings = &settings
	settingsMu.Unlock()

	return settings, nil
}

func (a *App) SaveSettings(settings AppSettings) error {
	settingsMu.Lock()
	currentSettings = &settings
	settingsMu.Unlock()

	settingsFile := a.getSettingsFilePath()
	data, err := json.MarshalIndent(settings, "", "  ")
	if err != nil {
		return err
	}

	return os.WriteFile(settingsFile, data, 0644)
}

func (a *App) GetDefaultSettings() AppSettings {
	return getDefaultSettings()
}

func (a *App) ResetSettings() error {
	defaults := getDefaultSettings()
	return a.SaveSettings(defaults)
}

