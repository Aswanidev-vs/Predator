/* -------------------- Template & Organization -------------------- */

func (a *App) ValidateTemplate(template string) error {
	invalidChars := []string{"<", ">", ":", "\"", "|", "?", "*"}
	for _, char := range invalidChars {
		if strings.Contains(template, char) {
			return fmt.Errorf("template contains invalid character: %s", char)
		}
	}

	requiredVars := []string{"%(ext)s"}
	for _, v := range requiredVars {
		if !strings.Contains(template, v) {
			return fmt.Errorf("template must contain %s", v)
		}
	}

	return nil
}

func (a *App) PreviewTemplate(template string, videoInfo VideoInfo) (string, error) {
	if err := a.ValidateTemplate(template); err != nil {
		return "", err
	}

	preview := template
	preview = strings.ReplaceAll(preview, "%(title)s", videoInfo.Title)
	preview = strings.ReplaceAll(preview, "%(id)s", "dQw4w9WgXcQ")
	preview = strings.ReplaceAll(preview, "%(ext)s", "mp4")
	preview = strings.ReplaceAll(preview, "%(resolution)s", "1080p")

	return preview, nil
}

func (a *App) GetOrganizedOutputPath(baseDir string, videoInfo VideoInfo, playlistTitle string) (string, error) {
	settings, err := a.GetSettings()
	if err != nil {
		return "", err
	}

	var outputDir string

	switch settings.OrganizeBy {
	case "channel":
		outputDir = filepath.Join(baseDir, "Channels", "Unknown")
	case "playlist":
		if playlistTitle != "" {
			outputDir = filepath.Join(baseDir, "Playlists", sanitizeFilename(playlistTitle))
		} else {
			outputDir = filepath.Join(baseDir, "Singles")
		}
	case "date":
		now := time.Now()
		outputDir = filepath.Join(baseDir, now.Format("2006"), now.Format("01-2006"))
	default:
		outputDir = baseDir
	}

	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return "", err
	}

	return outputDir, nil
}

func sanitizeFilename(name string) string {
	invalid := []string{"<", ">", ":", "\"", "|", "?", "*", "\\", "/"}
	result := name
	for _, char := range invalid {
		result = strings.ReplaceAll(result, char, "_")
	}
	return strings.TrimSpace(result)
}

