func (a *App) FetchVideoInfo(url string) (*VideoInfo, error) {
	ctx, cancel := context.WithTimeout(context.Background(), fetchTimeout)
	defer cancel()

	result, err := ytdlp.New().DumpJSON().Run(ctx, url)
	if err != nil {
		return nil, err
	}

	var info struct {
		Title    string  `json:"title"`
		Duration float64 `json:"duration"`
		Formats  []struct {
			Height         *int   `json:"height"`
			Width          *int   `json:"width"`
			Filesize       *int64 `json:"filesize"`
			FilesizeApprox *int64 `json:"filesize_approx"`
			Vcodec         string `json:"vcodec"`
			Acodec         string `json:"acodec"`
			Ext            string `json:"ext"`
		} `json:"formats"`
	}

	if err := json.Unmarshal([]byte(result.Stdout), &info); err != nil {
		return nil, err
	}

	if info.Title == "" {
		return nil, fmt.Errorf("no video found at URL")
	}

	resMap := make(map[string]string)
	resHeightMap := make(map[int]string)

	for _, f := range info.Formats {
		if f.Vcodec != "none" && f.Height != nil && *f.Height > 0 {
			res := fmt.Sprintf("%dp", *f.Height)
			var size int64 = 0
			if f.Filesize != nil && *f.Filesize > 0 {
				size = *f.Filesize
			} else if f.FilesizeApprox != nil && *f.FilesizeApprox > 0 {
				size = *f.FilesizeApprox
			}

			existingSize := parseSizeString(resMap[res])
			if size > existingSize {
				if size > 0 {
					resMap[res] = formatBytes(float64(size))
					resHeightMap[*f.Height] = formatBytes(float64(size))
				} else {
					resMap[res] = "Unknown"
					resHeightMap[*f.Height] = "Unknown"
				}
			}
		}
	}

	var heights []int
	for h := range resHeightMap {
		heights = append(heights, h)
	}

	for i := 0; i < len(heights); i++ {
		for j := i + 1; j < len(heights); j++ {
			if heights[i] > heights[j] {
				heights[i], heights[j] = heights[j], heights[i]
			}
		}
	}

	opts := []string{}
	for _, h := range heights {
		res := fmt.Sprintf("%dp", h)
		size := resHeightMap[h]
		opts = append(opts, fmt.Sprintf("%s (%s)", res, size))
	}
	opts = append(opts, "best (Unknown)")

	return &VideoInfo{
		Title:       info.Title,
		Duration:    info.Duration,
		Resolutions: opts,
	}, nil
}

func (a *App) FetchPlaylistInfo(url string) (*PlaylistInfo, error) {
	ctx, cancel := context.WithTimeout(context.Background(), fetchTimeout*2)
	defer cancel()

	result, err := ytdlp.New().
		DumpJSON().
		FlatPlaylist().
		Run(ctx, url)
	if err != nil {
		return nil, fmt.Errorf("failed to fetch playlist: %w", err)
	}

	lines := strings.Split(result.Stdout, "\n")

	var playlistTitle, playlistID string
	videos := []PlaylistVideo{}

	for i, line := range lines {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}

		if i == 0 {
			var playlistMeta struct {
				Title   string `json:"title"`
				ID      string `json:"id"`
				Entries []struct {
					ID       string `json:"id"`
					Title    string `json:"title"`
					Duration int    `json:"duration"`
				} `json:"entries"`
			}

			if err := json.Unmarshal([]byte(line), &playlistMeta); err != nil {
				continue
			}

			playlistTitle = playlistMeta.Title
			playlistID = playlistMeta.ID

			for _, entry := range playlistMeta.Entries {
				if entry.ID == "" {
					continue
				}
				videos = append(videos, PlaylistVideo{
					ID:       entry.ID,
					Title:    entry.Title,
					Duration: entry.Duration,
					URL:      fmt.Sprintf("https://youtube.com/watch?v=%s", entry.ID),
				})
			}
			continue
		}

		var entry struct {
			ID            string `json:"id"`
			Title         string `json:"title"`
			Duration      int    `json:"duration"`
			PlaylistID    string `json:"playlist_id"`
			PlaylistTitle string `json:"playlist_title"`
		}

		if err := json.Unmarshal([]byte(line), &entry); err != nil {
			continue
		}

		if playlistID == "" && entry.PlaylistID != "" {
			playlistID = entry.PlaylistID
		}
		if playlistTitle == "" && entry.PlaylistTitle != "" {
			playlistTitle = entry.PlaylistTitle
		}

		if entry.ID == "" {
			continue
		}

		videos = append(videos, PlaylistVideo{
			ID:       entry.ID,
			Title:    entry.Title,
			Duration: entry.Duration,
			URL:      fmt.Sprintf("https://youtube.com/watch?v=%s", entry.ID),
		})
	}

	if playlistID == "" {
		return nil, fmt.Errorf("no playlist found at URL")
	}

	return &PlaylistInfo{
		Title:      playlistTitle,
		ID:         playlistID,
		VideoCount: len(videos),
		Videos:     videos,
	}, nil
}

func (a *App) DownloadPlaylist(videos []PlaylistVideo, downloadType string, resolution string, audioFormat string) ([]string, error) {
	taskIDs := make([]string, 0, len(videos))

	for _, video := range videos {
		videoInfo, err := a.FetchVideoInfo(video.URL)
		if err != nil {
			log.Printf("Failed to fetch info for %s: %v", video.Title, err)
			continue
		}

		cleanRes := ""
		if downloadType == "Video" {
			cleanRes = extractResolution(resolution)
		}

		task := DownloadTask{
			URL:          video.URL,
			Title:        videoInfo.Title,
			Type:         downloadType,
			Resolution:   resolution,
			CleanRes:     cleanRes,
			AudioFormat:  audioFormat,
			AudioQuality: "0",
			VideoCodec:   "",
		}

		taskID, err := a.AddToQueue(task)
		if err != nil {
			log.Printf("Failed to add %s to queue: %v", video.Title, err)
			continue
		}

		taskIDs = append(taskIDs, taskID)
	}

	return taskIDs, nil
}

func (a *App) AddToQueue(task DownloadTask) (string, error) {
	initSemaphore()

	taskID := a.generateTaskID()
	atomic.AddUint64(&taskCounter, 1)

	queueItem := &QueueItem{
		TaskID:   taskID,
		Task:     task,
		Status:   "queued",
		Progress: 0,
		AddedAt:  time.Now(),
		Priority: 0,
	}

	queueMu.Lock()
	downloadQueue = append(downloadQueue, queueItem)
	queueMu.Unlock()

	wailsRuntime.EventsEmit(a.ctx, "task-added", taskID, task)

	go a.worker(task, taskID)

	return taskID, nil
}

func (a *App) CancelTask(taskID string) error {
	tasksMu.Lock()
	if cancel, ok := activeTasks[taskID]; ok {
		cancel()
		delete(activeTasks, taskID)
		tasksMu.Unlock()

		queueMu.Lock()
		for i, item := range downloadQueue {
			if item.TaskID == taskID {
				downloadQueue = append(downloadQueue[:i], downloadQueue[i+1:]...)
				break
			}
		}
		queueMu.Unlock()

		wailsRuntime.EventsEmit(a.ctx, "task-cancelled", taskID)
		return nil
	}
	tasksMu.Unlock()
	return fmt.Errorf("task not found")
}

func (a *App) worker(task DownloadTask, taskID string) {
	initSemaphore()

	<-sem
	defer func() { sem <- struct{}{} }()

	ctx, cancel := context.WithCancel(context.Background())
	tasksMu.Lock()
	activeTasks[taskID] = cancel
	tasksMu.Unlock()

	queueMu.Lock()
	for _, item := range downloadQueue {
		if item.TaskID == taskID {
			now := time.Now()
			item.Status = "downloading"
			item.StartedAt = &now
			break
		}
	}
	queueMu.Unlock()

	wailsRuntime.EventsEmit(a.ctx, "task-started", taskID)

	err := a.downloadWithProgress(ctx, task, taskID)

	tasksMu.Lock()
	delete(activeTasks, taskID)
	tasksMu.Unlock()

	queueMu.Lock()
	for _, item := range downloadQueue {
		if item.TaskID == taskID {
			now := time.Now()
			item.CompletedAt = &now
			if err != nil {
				item.Status = "error"
			} else {
				item.Status = "completed"
				item.Progress = 100
			}
			break
		}
	}
	queueMu.Unlock()

	if err != nil {
		if err == context.Canceled {
			wailsRuntime.EventsEmit(a.ctx, "task-cancelled", taskID)
		} else {
			errStr := err.Error()
			if strings.Contains(errStr, "codec") ||
				strings.Contains(errStr, "merge") ||
				strings.Contains(errStr, "ffmpeg") ||
				strings.Contains(errStr, "postprocessor") {
				wailsRuntime.EventsEmit(a.ctx, "task-error", taskID, "Failed: codec/merge error. Try lower resolution.")
			} else {
				wailsRuntime.EventsEmit(a.ctx, "task-error", taskID, truncateError(err.Error(), 50))
			}
		}
	} else {
		wailsRuntime.EventsEmit(a.ctx, "task-completed", taskID, task)

		var actualFilePath string
		var fileSize int64

		outDir := a.GetOutputDir()
		pattern := filepath.Join(outDir, "*"+strings.ReplaceAll(task.Title, " ", "*")+"*")
		if files, err := filepath.Glob(pattern); err == nil && len(files) > 0 {
			var largestFile string
			var largestSize int64
			for _, f := range files {
				if info, err := os.Stat(f); err == nil && !info.IsDir() {
					if info.Size() > largestSize {
						largestSize = info.Size()
						largestFile = f
					}
				}
			}
			if largestFile != "" {
				actualFilePath = largestFile
				fileSize = largestSize
			}
		}

		if actualFilePath == "" {
			if entries, err := os.ReadDir(outDir); err == nil {
				var mostRecentFile string
				var mostRecentTime time.Time
				for _, entry := range entries {
					if !entry.IsDir() {
						info, err := entry.Info()
						if err == nil {
							if info.ModTime().After(mostRecentTime) {
								mostRecentTime = info.ModTime()
								mostRecentFile = filepath.Join(outDir, entry.Name())
							}
						}
					}
				}
				if mostRecentFile != "" {
					actualFilePath = mostRecentFile
					if info, err := os.Stat(mostRecentFile); err == nil {
						fileSize = info.Size()
					}
				}
			}
		}

		historyItem := DownloadHistory{
			ID:           taskID,
			URL:          task.URL,
			Title:        task.Title,
			Type:         task.Type,
			Resolution:   task.Resolution,
			AudioFormat:  task.AudioFormat,
			FilePath:     actualFilePath,
			FileSize:     fileSize,
			DownloadedAt: time.Now(),
			Status:       "completed",
		}

		a.SaveToHistory(historyItem)
	}
}

func (a *App) downloadWithProgress(ctx context.Context, task DownloadTask, taskID string) error {
	outDir := a.GetOutputDir()

	var formatStr string
	if task.Type == "Video" {
		formatStr = buildVideoFormatString(task.CleanRes, true)
	} else {
		formatStr = buildAudioFormatString(task.AudioFormat)
	}

	dl := ytdlp.New().
		Format(formatStr).
		Output(filepath.Join(outDir, "%(title)s [%(id)s].%(ext)s")).
		ProgressFunc(progressUpdateInterval, func(p ytdlp.ProgressUpdate) {
			percent := p.Percent()

			eta := "Unknown"
			if p.ETA() > 0 {
				eta = formatETA(p.ETA())
			}

			update := ProgressUpdate{
				TaskID:  taskID,
				Percent: percent,
				Status:  "downloading",
				Speed:   "Unknown",
				ETA:     eta,
			}

			wailsRuntime.EventsEmit(a.ctx, "progress-update", update)

			queueMu.Lock()
			for _, item := range downloadQueue {
				if item.TaskID == taskID {
					item.Progress = percent
					break
				}
			}
			queueMu.Unlock()
		})

	if task.Type == "Audio" && task.AudioFormat == "mp3" {
		dl = dl.ExtractAudio().AudioFormat("mp3")
	} else if task.Type == "Audio" && task.AudioFormat == "wav" {
		dl = dl.ExtractAudio().AudioFormat("wav")
	}

	result, err := dl.Run(ctx, task.URL)
	if err != nil {
		return fmt.Errorf("download failed: %w (output: %s)", err, result.Stderr)
	}

	return nil
}

func formatBytes(b float64) string {
	const unit = 1024
	if b < unit {
		return fmt.Sprintf("%.0f B", b)
	}
	div, exp := float64(unit), 0
	for n := b / unit; n >= unit; n /= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f %ciB", b/div, "KMGT"[exp])
}

func formatETA(d time.Duration) string {
	s := int64(d.Seconds())
	h := s / 3600
	m := (s % 3600) / 60
	sec := s % 60
	if h > 0 {
		return fmt.Sprintf("%02d:%02d:%02d", h, m, sec)
	}
	return fmt.Sprintf("%02d:%02d", m, sec)
}

func formatSpeed(speed float64) string {
	return formatBytes(speed) + "/s"
}

func parseSizeString(sizeStr string) int64 {
	if sizeStr == "" || sizeStr == "Unknown" {
		return 0
	}
	sizeStr = strings.TrimPrefix(sizeStr, "~")
	re := regexp.MustCompile(`([\d.]+)\s*([KMGT]?)i?B`)
	matches := re.FindStringSubmatch(sizeStr)
	if len(matches) < 3 {
		return 0
	}
	val, err := strconv.ParseFloat(matches[1], 64)
	if err != nil {
		return 0
	}
	multiplier := float64(1024)
	switch matches[2] {
	case "K":
		multiplier = 1024
	case "M":
		multiplier = 1024 * 1024
	case "G":
		multiplier = 1024 * 1024 * 1024
	case "T":
		multiplier = 1024 * 1024 * 1024 * 1024
	default:
		multiplier = 1
	}
	return int64(val * multiplier)
}

func truncateError(err string, maxLen int) string {
	if len(err) <= maxLen {
		return err
	}
	return err[:maxLen] + "..."
}

func extractResolution(resolution string) string {
	re := regexp.MustCompile(`^(\d+)p`)
	matches := re.FindStringSubmatch(resolution)
	if len(matches) > 1 {
		return matches[1]
	}
	if strings.HasPrefix(resolution, "best") {
		return "best"
	}
	return ""
}

