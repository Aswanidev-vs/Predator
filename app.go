func (a *App) SubscribeToChannel(channelID, channelName string, autoDownload bool) error {
	subs, err := a.GetChannelSubscriptions()
	if err != nil {
		return err
	}

	for _, sub := range subs {
		if sub.ChannelID == channelID {
			return fmt.Errorf("already subscribed to this channel")
		}
	}

	newSub := ChannelSubscription{
		ChannelID:    channelID,
		ChannelName:  channelName,
		AddedAt:      time.Now(),
		AutoDownload: autoDownload,
		LastChecked:  time.Now(),
	}

	subs = append(subs, newSub)

	subFile := a.getSubscriptionsFilePath()
	data, err := json.MarshalIndent(subs, "", "  ")
	if err != nil {
		return err
	}

	return os.WriteFile(subFile, data, 0644)
}

