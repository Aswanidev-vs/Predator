func (a *App) SearchYouTube(query string, filters map[string]string) ([]SearchResult, error) {
	ctx, cancel := context.WithTimeout(context.Background(), fetchTimeout*2)
	defer cancel()

	log.Printf("Searching YouTube for: %s", query)

	searchQuery := fmt.Sprintf("ytsearch10:%s", query)

	a.AddSearchHistory(query)

	result, err := ytdlp.New().
		DumpJSON().
		FlatPlaylist().
		Run(ctx, searchQuery)

	if err != nil {
		log.Printf("Search error: %v", err)
		return nil, fmt.Errorf("search failed: %w", err)
	}

	lines := strings.Split(result.Stdout, "\n")
	results := []SearchResult{}

	for _, line := range lines {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}

		var entry struct {
			ID          string `json:"id"`
			Title       string `json:"title"`
			Channel     string `json:"channel"`
			Duration    int    `json:"duration"`
			Thumbnail   string `json:"thumbnail"`
			ViewCount   int64  `json:"view_count"`
			UploadDate  string `json:"upload_date"`
			Description string `json:"description"`
		}

		if err := json.Unmarshal([]byte(line), &entry); err != nil {
			continue
		}

		if entry.ID == "" {
			continue
		}

		results = append(results, SearchResult{
			ID:          entry.ID,
			Title:       entry.Title,
			Channel:     entry.Channel,
			Duration:    entry.Duration,
			Thumbnail:   entry.Thumbnail,
			ViewCount:   entry.ViewCount,
			UploadDate:  entry.UploadDate,
			Description: entry.Description,
			URL:         fmt.Sprintf("https://youtube.com/watch?v=%s", entry.ID),
		})
	}

	log.Printf("Found %d search results", len(results))
	return results, nil
}

