func (a *App) PauseTask(taskID string) error {
	tasksMu.Lock()
	if cancel, ok := activeTasks[taskID]; ok {
		cancel()
		delete(activeTasks, taskID)
	}
	tasksMu.Unlock()

	queueMu.Lock()
	for _, item := range downloadQueue {
		if item.TaskID == taskID {
			item.Status = "paused"
			break
		}
	}
	queueMu.Unlock()

	return nil
}

func (a *App) ResumeTask(taskID string) error {
	queueMu.Lock()
	var task *QueueItem
	for _, item := range downloadQueue {
		if item.TaskID == taskID && item.Status == "paused" {
			task = item
			break
		}
	}
	queueMu.Unlock()

	if task == nil {
		return fmt.Errorf("task not found or not paused")
	}

	task.Status = "queued"
	go a.worker(task.Task, taskID)

	return nil
}

func (a *App) ReorderQueue(taskIDs []string) error {
	queueMu.Lock()
	defer queueMu.Unlock()

	itemMap := make(map[string]*QueueItem)
	for _, item := range downloadQueue {
		itemMap[item.TaskID] = item
	}

	newQueue := make([]*QueueItem, 0, len(taskIDs))
	for i, id := range taskIDs {
		if item, ok := itemMap[id]; ok {
			item.Priority = i
			newQueue = append(newQueue, item)
		}
	}

	downloadQueue = newQueue
	return nil
}

