func (a *App) AddSearchHistory(query string) error {
	if query == "" {
		return nil
	}

	history, err := a.GetSearchHistory()
	if err != nil {
		return err
	}

	for i, h := range history {
		if h.Query == query {
			history = append(history[:i], history[i+1:]...)
			break
		}
	}

	newEntry := SearchHistory{
		Query:     query,
		Timestamp: time.Now(),
	}
	history = append([]SearchHistory{newEntry}, history...)

	settings, _ := a.GetSettings()
	limit := settings.SearchHistoryLimit
	if limit <= 0 {
		limit = 50
	}
	if len(history) > limit {
		history = history[:limit]
	}

	historyFile := a.getSearchHistoryFilePath()
	data, err := json.MarshalIndent(history, "", "  ")
	if err != nil {
		return err
	}

	return os.WriteFile(historyFile, data, 0644)
}

func (a *App) ClearSearchHistory() error {
	historyFile := a.getSearchHistoryFilePath()
	return os.Remove(historyFile)
}

